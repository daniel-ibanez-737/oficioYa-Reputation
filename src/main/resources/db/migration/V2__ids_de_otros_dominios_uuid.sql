-- Ids de otros dominios como UUID, igual que en Identity, Worker y Service (integración del Sprint 5).
-- No hay datos reales todavía: se recrean las tablas. Los datos de demo los vuelve a cargar R__datos_demo.

DROP TABLE IF EXISTS penalizacion CASCADE;
DROP TABLE IF EXISTS reporte_resena CASCADE;
DROP TABLE IF EXISTS resena CASCADE;
DROP TABLE IF EXISTS reputacion_contratante CASCADE;
DROP TABLE IF EXISTS reputacion_trabajador CASCADE;
DROP TABLE IF EXISTS reputacion CASCADE;
DROP TABLE IF EXISTS servicio_calificable CASCADE;


CREATE TABLE servicio_calificable (
    id                         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id               UUID      NOT NULL,
    trabajador_id              UUID      NOT NULL,
    contratante_id             UUID      NOT NULL,
    fecha_cumplida             TIMESTAMP NOT NULL,
    calificado_por_trabajador  BOOLEAN   NOT NULL DEFAULT FALSE,
    calificado_por_contratante BOOLEAN   NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_servicio_solicitud UNIQUE (solicitud_id)
);

-- Herencia Reputacion -> ReputacionTrabajador / ReputacionContratante (tabla por subclase).
CREATE TABLE reputacion (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo                    VARCHAR(20) NOT NULL,
    promedio_calificaciones FLOAT       NOT NULL DEFAULT 0,
    total_resenas           INTEGER     NOT NULL DEFAULT 0,
    fecha_actualizacion     TIMESTAMP   NOT NULL,
    CONSTRAINT ck_reputacion_tipo CHECK (tipo IN ('TRABAJADOR', 'CONTRATANTE'))
);

CREATE TABLE reputacion_trabajador (
    id                     INTEGER PRIMARY KEY,
    trabajador_id          UUID        NOT NULL,
    penalizacion_acumulada FLOAT       NOT NULL DEFAULT 0,
    estado                 VARCHAR(20) NOT NULL,
    fecha_pausado          TIMESTAMP,
    CONSTRAINT fk_reputacion_trabajador FOREIGN KEY (id) REFERENCES reputacion (id),
    CONSTRAINT uk_reputacion_trabajador UNIQUE (trabajador_id),
    CONSTRAINT ck_reputacion_trabajador_estado CHECK (estado IN ('ACTIVO', 'PAUSADO'))
);

CREATE TABLE reputacion_contratante (
    id             INTEGER PRIMARY KEY,
    contratante_id UUID    NOT NULL,
    CONSTRAINT fk_reputacion_contratante FOREIGN KEY (id) REFERENCES reputacion (id),
    CONSTRAINT uk_reputacion_contratante UNIQUE (contratante_id)
);

CREATE TABLE resena (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          UUID         NOT NULL,
    servicio_id     INTEGER      NOT NULL,
    reputacion_id   INTEGER      NOT NULL,
    autor_id        UUID         NOT NULL,
    tipo_autor      VARCHAR(20)  NOT NULL,
    calificado_id   UUID         NOT NULL,
    tipo_calificado VARCHAR(20)  NOT NULL,
    puntuacion      INTEGER      NOT NULL,
    comentario      VARCHAR(500),
    visible         BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_creacion  TIMESTAMP    NOT NULL,
    CONSTRAINT uk_resena_codigo UNIQUE (codigo),
    -- Una reseña por parte en cada servicio (máximo 2 por servicio).
    CONSTRAINT uk_resena_servicio_autor UNIQUE (servicio_id, tipo_autor),
    CONSTRAINT fk_resena_servicio FOREIGN KEY (servicio_id) REFERENCES servicio_calificable (id),
    CONSTRAINT fk_resena_reputacion FOREIGN KEY (reputacion_id) REFERENCES reputacion (id),
    CONSTRAINT ck_resena_puntuacion CHECK (puntuacion BETWEEN 1 AND 5),
    CONSTRAINT ck_resena_tipo_autor CHECK (tipo_autor IN ('TRABAJADOR', 'CONTRATANTE')),
    CONSTRAINT ck_resena_tipo_calificado CHECK (tipo_calificado IN ('TRABAJADOR', 'CONTRATANTE'))
);

CREATE INDEX ix_resena_reputacion ON resena (reputacion_id);

CREATE TABLE reporte_resena (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resena_id        INTEGER      NOT NULL,
    reportante_id    UUID         NOT NULL,
    motivo           VARCHAR(20)  NOT NULL,
    descripcion      VARCHAR(500),
    estado           VARCHAR(20)  NOT NULL,
    fecha_reporte    TIMESTAMP    NOT NULL,
    moderador_id     UUID   ,
    resultado        VARCHAR(20),
    fecha_resolucion TIMESTAMP,
    CONSTRAINT fk_reporte_resena FOREIGN KEY (resena_id) REFERENCES resena (id),
    CONSTRAINT ck_reporte_motivo CHECK (motivo IN ('FALSA', 'INAPROPIADA', 'OFENSIVA', 'OTRO')),
    CONSTRAINT ck_reporte_estado CHECK (estado IN ('PENDIENTE', 'EN_REVISION', 'RESUELTO')),
    CONSTRAINT ck_reporte_resultado CHECK (resultado IN ('RESENA_RETIRADA', 'RESENA_MANTENIDA'))
);

CREATE INDEX ix_reporte_estado ON reporte_resena (estado);

CREATE TABLE penalizacion (
    id                       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reputacion_trabajador_id INTEGER      NOT NULL,
    solicitud_id             UUID         NOT NULL,
    puntos                   FLOAT        NOT NULL,
    motivo                   VARCHAR(255) NOT NULL,
    fecha_hora_servicio      TIMESTAMP    NOT NULL,
    fecha_cancelacion        TIMESTAMP    NOT NULL,
    fecha_aplicacion         TIMESTAMP    NOT NULL,
    CONSTRAINT fk_penalizacion_reputacion FOREIGN KEY (reputacion_trabajador_id) REFERENCES reputacion_trabajador (id),
    -- Una sola penalización por solicitud cancelada (evita aplicar dos veces el mismo aviso).
    CONSTRAINT uk_penalizacion_solicitud UNIQUE (solicitud_id)
);
